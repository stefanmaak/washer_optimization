"""Generates the pythonLab process (source code) the orchestrator in cage2 executes for one test.

The orchestrator rebuilds the process class from its source and instantiates it without arguments, so all
parameters are written into the source as literals.
"""

from dataclasses import dataclass

from interface_service.models import TestRequest


@dataclass
class ProcessParameters:
    protocol_name: str
    """Name under which the washing protocol is stored on the BlueWasher."""
    start_position: int
    """Position of the lidded plate in Hotel2."""
    squid: str
    """Squid used for all checks, e.g. Squid1."""
    empty_check_protocol: str
    coverage_check_protocol: str
    squid_project: str


def process_class_name(run_id: str) -> str:
    return f"WashOpt_{run_id}"


def generate_process_source(run_id: str, request: TestRequest, params: ProcessParameters) -> str:
    """Hotel2 -> coverage check -> n_washes x (BlueWasher wash, empty check, coverage check if requested) -> Fridge.
    All checks run on the squid given in params.
    request.coverage_checks always contains 0 (before the first wash) and n_washes."""
    name = process_class_name(run_id)
    checks_after_wash = [c for c in request.coverage_checks if c > 0]
    squid = f"self.{params.squid.lower()}"  # attribute of WashingProcess, e.g. self.squid1
    empty_check = _squid_step(squid, params.empty_check_protocol, params.squid_project)
    coverage_check = _squid_step(squid, params.coverage_check_protocol, params.squid_project)

    return f'''"""Generated by the washing optimization interface service for run {run_id}."""

from interface_service.process_base import WashingProcess


class {name}(WashingProcess):
    def __init__(self):
        super().__init__(process_name={name!r})

    def init_service_resources(self):
        super().init_service_resources()
        self.plate.set_start_position(self.hotel2, {params.start_position})

    def process(self):
        n_washes = {request.n_washes}
        # washes after which the coverage is checked (there is always one before the first wash, too)
        coverage_checks = {checks_after_wash!r}

        cont = self.plate
        self.robot_arm.move(cont, {squid}, lidded=False, read_barcode=True)
        {coverage_check}
        for wash in range(1, n_washes + 1):
            self.robot_arm.move(cont, self.bluewasher, lidded=False)
            self.bluewasher.run_protocol(labware=cont, protocol={params.protocol_name!r})
            self.robot_arm.move(cont, {squid}, lidded=False)
            {empty_check}
            if wash in coverage_checks:
                {coverage_check}
        self.robot_arm.move(cont, self.fridge, lidded=True)
'''


def _squid_step(squid: str, protocol: str, project: str) -> str:
    return f"{squid}.run_protocol(labware=cont, protocol={protocol!r}, project={project!r})"
